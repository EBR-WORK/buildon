/**
 * Lists the images and videos in public/ so the admin's pickers can offer them.
 *
 * A static export has no server to ask "what is in public?", so the answer is
 * baked in at build time. Run it whenever media is added:
 *
 *   npm run media
 *
 * It is also wired into `npm run build`, so a deploy can never ship a picker
 * that disagrees with the folder.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = "public";
const EXT = /\.(webp|png|jpe?g|svg)$/i;

/* Videos are listed but never inlined — see VideoField. An mp4 is two orders of
   magnitude past what a draft in localStorage can carry, so the picker offers
   the files already committed rather than pretending to hold a new one. */
const VIDEO_EXT = /\.(mp4|webm)$/i;

/** Folders worth offering. Everything else is page furniture, not content. */
const FOLDERS = ["products", "projects", "blog", "brand", "clients", "career", "about"];

function walk(dir, match) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full, match));
    else if (match.test(entry.name)) out.push(full);
  }
  return out;
}

/** Every matching file under the offered folders, as a web path. */
function collect(match) {
  return FOLDERS.flatMap((folder) => {
    const dir = path.join(ROOT, folder);
    return fs.existsSync(dir) ? walk(dir, match) : [];
  })
    .map((file) => "/" + path.relative(ROOT, file).split(path.sep).join("/"))
    .sort();
}

const files = collect(EXT);
const videos = collect(VIDEO_EXT);

const list = (entries) => entries.map((f) => `  ${JSON.stringify(f)},`).join("\n");

const body = `/**
 * Generated by scripts/media-manifest.mjs — do not edit by hand.
 *
 * Every image and video in public/ the admin may choose from. Regenerate with
 * \`npm run media\` after adding or removing files.
 */

export const mediaLibrary: readonly string[] = [
${list(files)}
];

/** Videos are chosen, never uploaded into the draft. See VideoField. */
export const videoLibrary: readonly string[] = [
${list(videos)}
];
`;

fs.writeFileSync("src/lib/cms/media.ts", body);
console.log(`media manifest: ${files.length} images, ${videos.length} videos`);
